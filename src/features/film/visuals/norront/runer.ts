/** SVG-sti for en rune plassert i (x, y) med høyde h. */
export function runeSti(rune: Rune, x: number, y: number, h: number) {
    const s = h / 2;
    return rune
        .map((linje) =>
            linje
                .map(([a, b], i) => `${i === 0 ? 'M' : 'L'} ${(x + a * s).toFixed(1)} ${(y + b * s).toFixed(1)}`)
                .join(' ')
        )
        .join(' ');
}
